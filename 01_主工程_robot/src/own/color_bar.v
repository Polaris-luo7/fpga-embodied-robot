//=============================================================================
// color_bar.v —— 纯色轮播选择器（实验 12：任务一 DoD 第 7 项「颜色位序」）
//-----------------------------------------------------------------------------
// 目的：用一个"颜色已知"的信号替换图像数据，投到屏上，从而**判定 R/B 位序**。
//   背景：`任务一_上板记录.md` §三.2 记着一条未定论的分歧 ——
//     例程 .cst 的 TFT_rgb 位序与官方管脚表**相反**（例程 rgb[15]=N14、
//     官方表 rgb[15]=U17，两组互为倒序）。本工程采用了**官方管脚表**，
//     实拍观感正常但**从未严格验证**。
//
// 位置：disp_driver 输出之后、osd_overlay 之前（只动显示端，不碰摄像头表）。
//
// ★★ 本工程打包约定（与顶层 `v_rgb565 = {video_b, video_g, video_r}` 一致）：
//      bit[15:11] = B[4:0]      bit[10:5] = G[5:0]      bit[4:0] = R[4:0]
//    ⇒ 在本约定下：  纯红 = 16'h001F    纯蓝 = 16'hF800
//      （**与常见"R 在高位"的 RGB565 写法相反** —— 这正是本次要验的东西，
//        所以参数按"意图"命名并把期望值写死在注释里，不要照抄网上的 0xF800=红。）
//
// 判读方法（用户烧板后拍一个完整轮播）：
//    第 1 色应是**红**、第 3 色应是**蓝**。
//    · 第1色显红、第3色显蓝  ⇒ **本工程位序正确**（官方管脚表对）
//    · 第1色显蓝、第3色显红  ⇒ **R/B 倒了**，改打包顺序是一行的事
//      （顶层 `v_rgb565 = {video_r, video_g, video_b}` 或改 .cst 的位序）
//    · 都不对（如显绿/黄）    ⇒ 位序更复杂，需回看屏端 J1 逐针表
//
// 轮播顺序与时长：红 → 绿 → 蓝 → 白 → 黑，每色 ROLL_SEC 秒（默认 1 s），
//                 一轮 5 色 = 5 s。用户拍 ≥6 s 或连拍 5 张即可覆盖一轮。
//
// 关掉方式：顶层 `COLOR_MODE = 0` ⇒ 本模块退化为**纯组合透传**（零新增逻辑、
//           计数器被折叠掉），OSD 与图像链路完全不受影响。
//
// 注意：OSD 叠加在本模块**之后**，所以纯色之上仍有 FPS/PCLK 文字 ——
//       顺便可观察描边在 5 种背景下的可读性（见记录文件的观察表）。
//=============================================================================
// 2026-10-03 WorkBuddy 新建（实验 12，W2 离线项）
//=============================================================================

`timescale 1ns/1ps

module color_bar #(
    // 0 = FIXED：纯透传（测试结束后改回 0 即关掉本功能）
    // 1 = AUTO_ROLL：按计数器自动轮播 5 色
    parameter integer COLOR_MODE = 1,

    // 显示域像素时钟频率（本工程 clk_tft = 33 MHz）
    parameter integer CLK_HZ     = 33_000_000,

    // 每色持续秒数
    parameter integer ROLL_SEC   = 1,

    // ---- 五个纯色（**按本工程 {B,G,R} 打包约定的期望值**）----
    parameter [15:0]  C_RED = 16'h001F,   // R=31 → [4:0]=11111
    parameter [15:0]  C_GRN = 16'h07E0,   // G=63 → [10:5]=111111
    parameter [15:0]  C_BLU = 16'hF800,   // B=31 → [15:11]=11111
    parameter [15:0]  C_WHT = 16'hFFFF,
    parameter [15:0]  C_BLK = 16'h0000
)(
    input  wire        pclk,
    input  wire        rst_n,
    input  wire        de_in,
    input  wire [15:0] rgb_in,
    output wire        de_out,
    output wire [15:0] rgb_out,
    output reg  [2:0]  idx_dbg,      // 当前色序号 0..4（仅调试/仿真用）
    output wire        roll_active   // 1 = 正在轮播（COLOR_MODE!=0 时为常 1）
);

    // 每色持续拍数 = 时钟频率 × 秒
    localparam integer TICKS = CLK_HZ * ROLL_SEC;

    // COLOR_MODE 是参数（常量）⇒ 为 0 时下面的计数器/比较会被综合整体折叠
    assign roll_active = (COLOR_MODE != 0);

    //------------------------------------------------------------------
    // 1. 轮播计数器（显示域）
    //------------------------------------------------------------------
    reg [31:0] cnt;

    always @(posedge pclk or negedge rst_n) begin
        if (!rst_n) begin
            cnt     <= 32'd0;
            idx_dbg <= 3'd0;
        end else if (!roll_active) begin
            cnt     <= 32'd0;
            idx_dbg <= 3'd0;
        end else if (cnt >= (TICKS[31:0] - 32'd1)) begin
            cnt     <= 32'd0;
            idx_dbg <= (idx_dbg >= 3'd4) ? 3'd0 : (idx_dbg + 3'd1);
        end else begin
            cnt     <= cnt + 32'd1;
        end
    end

    //------------------------------------------------------------------
    // 2. 颜色查表（组合）
    //------------------------------------------------------------------
    reg [15:0] sel;

    always @(*) begin
        case (idx_dbg)
            3'd0:    sel = C_RED;
            3'd1:    sel = C_GRN;
            3'd2:    sel = C_BLU;
            3'd3:    sel = C_WHT;
            3'd4:    sel = C_BLK;
            default: sel = C_RED;
        endcase
    end

    //------------------------------------------------------------------
    // 3. 输出：轮播时输出纯色，否则**纯组合透传**（不引入任何延迟）
    //    注意 rgb_out 是 wire + 组合选择 ⇒ 透传模式下与原路径逐拍等价，
    //    不会把像素流水线推迟一拍（避免横向错位一格）。
    //------------------------------------------------------------------
    assign de_out  = de_in;
    assign rgb_out = roll_active ? sel : rgb_in;

endmodule
