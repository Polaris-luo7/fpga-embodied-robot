// Create Date   : 2026-10-14
// Description   : 任务五 视觉前端 V1 —— 阶段一 第 1 步
//                 (1) RGB565 → 灰度（(R+2G+B)/4 近似，只需加法与移位）
//                 (2) 目标色判据（R 同时显著大于 G 和 B，且不太暗）
//                 (3) 诊断显示模式选择（透传 / 灰度 / 目标色二值 / 灰+框 / 原图+框）
//
// ★★ 位序（本工程专有，务必注意）★★
//     像素字 = { B[4:0], G[5:0], R[4:0] }   —— R 在【低位】、B 在【高位】
//     依据（顶层 ov5640_ddr3_tft.v 原文）：
//       · 第 523 行  wire [15:0] v_rgb565 = {video_b, video_g, video_r};
//       · 第 531 行  "⇒ 纯红 = 16'h001F、纯蓝 = 16'hF800（与常见 RGB565 相反）"
//     若按常见 RGB565（R 在高位）解包，红/蓝判据会整体颠倒 —— 本模块最容易搞错的一点。
//
// ★★ 为什么是"纯组合"（无时钟、无寄存器）★★
//     本模块插在 DVP_Capture 的 DataPixel 与写 DDR3 的 FIFO 之间。
//     写 FIFO 的 strobe（DataValid）与地址（Xaddr/Yaddr）都来自 DVP_Capture，
//     若在此插入流水线寄存器而不把 strobe/地址一起打拍，画面会整体错位（每像素
//     valid 只占一拍、相邻 valid 间隔两拍，错一拍就完全对不上）。
//     纯组合 ⇒ 写入的像素与它自己的坐标**严格同拍**，零延迟、零错位。
//
// ★★ 关于时序（2026-10-14 实测记录）★★
//     初版用 BT.601 加权 (77R+150G+29B) 与"红度" (171R-22G-149B)，含 3 个常数乘法器。
//     结果把原本干净的 camera_pclk 域（基线 TNS = 0.000 / 0 端点）打成了
//     TNS = -117.502 ns / 32 个违例端点 —— 组合路径过长（约 11.5 ns 周期装不下）。
//     ⇒ 本版改为**纯加法/比较**实现，去掉全部乘法器。
//     若日后仍有余量不足，正确的加流水线方式是"数据 + strobe 一起打拍"，
//     但会让框与坐标差 1 像素，属于下策；优先继续削组合深度。
//
// 调参入口（上板只调这三个，不动结构）：
//     SHOW_MODE   : 0=原图透传（基线等价）1=灰度 2=目标色二值(白=目标) 3=灰度+框 4=原图+框
//     RED_MARGIN  : R 要比 G、B 各高出多少才算"目标色"，越大越严格（默认 60）
//     TH_GMIN     : 灰度下限，滤掉暗处噪点（默认 20）
////////////////////////////////////////////////////////////////////////////////

module vision_front #(
    parameter integer SHOW_MODE   = 3,    // 默认 3：灰度 + 目标包围框（信息量最大）
    parameter integer RED_MARGIN  = 60,   // R 相对 G/B 的最小优势（0~255）
    parameter integer TH_GMIN     = 40,   // 灰度下限（V11：20→40，砍暗区噪点；红板灰度≈160）
    parameter integer BOX_T       = 2     // 包围框线宽（像素）
)(
    input               clk,            // camera_pclk（仅用于"连续性过滤"的两个寄存器）
    input               rst_n,
    input               px_valid,       // = DataValid，每拍一个有效像素

    input      [15:0]   px,             // 原始像素 {B[4:0], G[5:0], R[4:0]}
    input      [10:0]   px_x,           // 像素列号（0..799）
    input      [10:0]   px_y,           // 像素行号（0..479）

    // 目标包围框（来自 vision_blob，逐帧更新；tgt_valid=0 时不画框）
    input               tgt_valid,
    input      [11:0]   tgt_xmin,
    input      [11:0]   tgt_xmax,
    input      [11:0]   tgt_ymin,
    input      [11:0]   tgt_ymax,

    output     [15:0]   disp_px,        // 诊断显示像素（送写 DDR3 的 FIFO）
    output              red_now,        // 本像素是否属于目标色（组合，与 px/px_x/px_y 同拍）
    output     [7:0]    gray_now        // 本像素灰度（组合）
);

    //------------------------------------------------------------------
    // 1. RGB565 解包（★ 注意本工程位序：R 在低位）
    //------------------------------------------------------------------
    wire [4:0] r5 = px[4:0];
    wire [5:0] g6 = px[10:5];
    wire [4:0] b5 = px[15:11];

    // 5/6 bit → 8 bit 扩展（复制高位补齐，误差 < 1LSB）
    wire [7:0] r8 = {r5, r5[4:2]};
    wire [7:0] g8 = {g6, g6[5:4]};
    wire [7:0] b8 = {b5, b5[4:2]};

    //------------------------------------------------------------------
    // 2. 灰度：Y ≈ (R + 2G + B) / 4     ← 只用 2 个加法器 + 移位，无乘法器
    //    （BT.601 权重 0.299/0.587/0.114 的整数近似 0.25/0.5/0.25）
    //------------------------------------------------------------------
    wire [9:0] y_sum = {2'd0, r8} + {1'd0, g8, 1'b0} + {2'd0, b8};   // 最大 1020
    wire [7:0] gray  = y_sum[9:2];                                   // ÷4

    //------------------------------------------------------------------
    // 3. 目标色判据 V2（2026-10-25 放宽）—— 覆盖 饱和红 / 朱红 / 玫红 / 粉红
    //
    //   判据： (5*G < 3*R) && (R > R_MIN) && (gray > TH_GMIN) && (B <= R + B_TOL)
    //
    //   · 第一条是核心：用 **G/R 比值** 判"红"，不用固定差值。
    //     比值对整体亮度和环境偏色都不敏感；一次淘汰 白/黄/肤/灰/蓝/绿。
    //     G/R < 0.6 才命中 ⇒
    //        饱和红 (~0.3) ✓   朱红/橙红 (~0.3) ✓   玫红 (~0.4) ✓   深粉 (~0.5) ✓
    //        皮肤   (~0.75) ✗  ← 刻意留的余量：放宽到 0.75 手就会一直被框住
    //   · 第二条：太暗的像素不算，防暗处噪点。
    //   · 第三条：允许 B 接近甚至略超 R ⇒ 放行 玫红/品红/粉红。
    //     （旧判据要求"R 比 B 高 60"，粉/玫红永远不达标 —— 这是上一版不出框的原因之一。）
    //
    //   ★ 现场想更严/更松，只改这两个常量：
    //       G_DIV / R_DIV   : 8/5 ⇒ 要求 G/R < 5/8 = 0.625（纯移位实现，零乘法器）
    //                         想更松用 1/1（G<R，会开始框住手/橙黄）
    //                         想更严用 1/2（G<R/2，只认很纯的红）
    //       B_TOL           : 32  ⇒ 允许蓝分量高出 R 多少；调 0 = 更偏"纯红"
    //       R_MIN           : 40  ⇒ 亮度下限
    //   ★ 为什么用移位不用乘法：本工程 camera_pclk 域是唯一时序净区，乘法器会把
    //     组合路径撑长、把净区打违例（实测过一次，96 个违例端点）。移位只需 1~2 级。
    //------------------------------------------------------------------
    localparam [7:0]   R_MIN  = 8'd28;    // 亮度下限（V6 从 40 降到 28：40 会砍掉偏暗一半的红）

    // ★ 2026-10-28 V10：门槛 0.8125 → 0.875（R − R/8，单个减法器，比原来的三路移位加法更省）
    //   实测依据：二值掩膜下红色纸板"边缘能过、内部不过"，只有零散白点；
    //   而同样判据下红色小球是**实心白块** ⇒ 判据形态没错，是纸板饱和度低于球，
    //   内部像素的 G/R 落在 0.8125 之外。门槛放到 0.875 把纸板内部也纳进来。
    //   白墙 G/R≈0.93 仍在门槛外（余量 0.055），灰度地面 G/R≈1 更远。
    //   ⚠️ 代价：肤色 G/R≈0.75 会命中 ⇒ 演示时手不要入镜。
    wire [8:0] r_thr = {1'b0, r8} - {2'b00, r8[7:3]};        // 0.875R（最大 223）

    //------------------------------------------------------------------
    // 3a. ★ 目标色判据 V9（2026-10-27 修噪点）
    //
    //   ★ V8 噪点回归的根因（已定位）：
    //     V8 的绝对差支 "R >= G+12" **没有亮度上限**。12 在暗部是 30% 的门槛，
    //     在亮部只有 7% —— 偏蓝环境下的白墙 R≈170,G≈158 差值正好 12，
    //     整面墙全部通过；而 RUN_MIN 连续过滤对"大片均匀白墙"完全无效。
    //     （V7 无此问题，正因它的绝对差支带 R<90 上限。）
    //
    //   ★ V9 的分工原则：**按亮度选判据，而不是两支无脑取或**
    //     ① 亮部/全亮度（R >= 96）→ 只用【比值】G < 0.8125·R
    //        比值是尺度无关的：白墙 G/R≈0.93 一律排除；
    //        饱和红 0.26、粉/玫红 0.52~0.67 都稳过。
    //     ② 暗部（28 <= R < 96）→ 只用【绝对差】R >= G+16 且 R >= B
    //        暗部饱和度被噪声抬高，比值失效，只能靠绝对差；
    //        差值 16 且 R>=B 能挡住暗灰、暗蓝背景布。
    //
    //   亮度下限 R_MIN = 28（40 会砍掉偏暗一半的红）。
    //------------------------------------------------------------------
    // ★ V9.1（2026-10-27 修布线）：结构回归"已成功布线"的 V8 单一组合形态，
    //   只补一个亮度上限 96 把白墙挡在绝对差支之外。
    //   （V9 用了两条独立 wire + 多一个 R>=B 比较器，布线器报 1 根网络布不通；
    //     等价功能、更少的中间网络，有助于布线收敛。）
    //
    //   ① 比值支（全亮度）：G < 0.8125·R   —— 尺度无关，白墙 G/R≈0.93 排除
    //   ② 绝对差支（仅暗部 R<96）：R >= G+16 —— 暗部比值失效，改用绝对差
    /* ★2026-10-28 V11：去掉暗部支路（R≥G+16 且 R<96）—— 它是满屏均匀白点的来源。
       暗区色度噪声很容易凑出 16 的差值，而 RUN_MIN 对这种"稀疏且均匀"的噪声无效
       （实测 v5 把 RUN_MIN 放到 4 之后整屏白点密度明显上升，正对应这条）。
       目标红板是亮的，暗支对它没有贡献，直接删掉；改为"过曝红"绝对差支 R≥G+30：
       板心过曝成 R≈250,G≈200 时差值 50 仍能过，而白墙 R−G≈12 稳稳排除。
       实测依据（屏摄取色）：红板 g/r≈0.65~0.72，地面 g/r≈1.01，两者分离度足够。 */
    wire [8:0] g30     = {1'b0, g8} + 9'd30;
    wire       diff_ok = ({1'b0, r8} >= g30);                   // 绝对红度（覆盖过曝区）
    /* ★2026-10-29 V12：把**蓝通道约束**加回来。
       这是历史遗留漏洞：V2 的判据本来有 `B <= R + B_TOL`，V9 修白墙噪点时把它删掉，
       之后判据只看 G 和 R ⇒ 蓝/紫/青色物体只要 G 相对 R 偏低就会被判成红色。
       实测（屏摄取色）：白板/墙背景 B/R≈1.6~2.0，红板 B/R≈1.2。
       取 1.5 作分界（`b_thr = R + R/2`），两边各留约 0.3 余量。
       若现场发现板子反而识别不到，说明板子 B/R 高于 1.5，把 1.5 抬到 1.8 即可。 */
    wire [8:0] b_thr   = {1'b0, r8} + {2'b00, r8[7:1]};         // 1.5·R
    wire       blue_ok = ({1'b0, b8} < b_thr);                  // 蓝分量不得接近红
    wire       red_any = (({1'b0, g8} < r_thr) || diff_ok) && blue_ok;

    wire       red_raw = red_any && (r8 >= R_MIN) && (gray > TH_GMIN);

    //------------------------------------------------------------------
    // 3b. ★ 连续性过滤 V2（2026-10-26）—— 同一行连续 ≥RUN_MIN 个像素都是红才承认
    //     作用：噪点在画面里呈"零散单点/双点"雪花，用行内连续计数可以基本清零；
    //           红物体内部是连续几十个像素，会完整保留成实心白块。
    //     实现：5 位行内计数器 + 一个"已达阈值"标志。零 BSRAM、零乘法器。
    //     代价：目标左右边缘各缩进 RUN_MIN-1 像素（对包围框/质心无实质影响）。
    //     ★ 调参：RUN_MIN 调大（8~12）= 更干净但小目标会消失；
    //             RUN_MIN 调小（3~4）= 更灵敏但雪花回来。**一次只动这一个**。
    //------------------------------------------------------------------
    localparam integer RUN_MIN = 6;      // 需要连续多少个红像素才承认（V11：复原到 6）

    reg [4:0] run;                       // 当前行内连续红像素计数（饱和到 31）
    reg       red_ok;                    // 本行已达标，保持到断点

    always @(posedge clk or negedge rst_n)
      if(!rst_n) begin
        run    <= 5'd0;
        red_ok <= 1'b0;
      end
      else if (px_valid) begin
        if (red_raw) begin
          if (run != 5'd31) run <= run + 5'd1;
          if (run >= (RUN_MIN-1)) red_ok <= 1'b1;
        end
        else begin
          run    <= 5'd0;
          red_ok <= 1'b0;
        end
      end

    assign red_now  = red_ok;
    assign gray_now = gray;

    //------------------------------------------------------------------
    // 4. 包围框（线宽 BOX_T）：只在框内、且落在四条边上时打白
    //------------------------------------------------------------------
    localparam [11:0] BOX_TW = BOX_T;      // 参数不能位选，先转成 12 位常量

    wire [11:0] x12 = {1'b0, px_x};
    wire [11:0] y12 = {1'b0, px_y};

    wire in_x = (x12 >= tgt_xmin) && (x12 <= tgt_xmax);
    wire in_y = (y12 >= tgt_ymin) && (y12 <= tgt_ymax);

    wire [11:0] xl = tgt_xmin + BOX_TW - 12'd1;   // 左边带右界
    wire [11:0] xr = tgt_xmax - BOX_TW + 12'd1;   // 右边带左界
    wire [11:0] yt = tgt_ymin + BOX_TW - 12'd1;
    wire [11:0] yb = tgt_ymax - BOX_TW + 12'd1;

    wire on_box = tgt_valid && in_x && in_y &&
                  ( (x12 <= xl) || (x12 >= xr) || (y12 <= yt) || (y12 >= yb) );

    //------------------------------------------------------------------
    // 5. 显示模式选择（纯组合；SHOW_MODE=0 时退化为透传 ⇒ 与基线图像通路功能等价）
    //------------------------------------------------------------------
    wire [15:0] gray565 = {gray[7:3], gray[7:2], gray[7:3]};   // ★ 位序 {B,G,R}
    wire [15:0] mask565 = red_now ? 16'hFFFF : 16'h0000;       // 白 = 目标色

    reg [15:0] disp_r;
    always @(*) begin
        case (SHOW_MODE)
            0: disp_r = px;                            // 原图透传（基线等价）
            1: disp_r = gray565;                       // 灰度
            2: disp_r = mask565;                       // 目标色二值
            3: disp_r = on_box ? 16'hFFFF : gray565;   // 灰度 + 目标框
            4: disp_r = on_box ? 16'hFFFF : px;        // 原图 + 目标框（演示用）
            default: disp_r = px;
        endcase
    end
    assign disp_px = disp_r;

endmodule